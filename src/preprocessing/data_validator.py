# ============================================================
# FIND PART 1 TRAINING WORKBOOK
# ============================================================

def find_training_workbook() -> Path:
    """
    Locate the STRICT training workbook generated by Part 1.
    """

    current_project = (
        Path(__file__).resolve().parents[2]
    )

    # Part 1 project is located beside Part 2.
    part1_project = (
        current_project.parent
        / "TAT_MS_INTERCITY"
    )

    if not part1_project.exists():
        raise FileNotFoundError(
            "Part 1 project was not found:\n"
            f"{part1_project}"
        )

    if not part1_project.is_dir():
        raise ValueError(
            "Part 1 path is not a directory:\n"
            f"{part1_project}"
        )

    matches = list(
        part1_project.rglob(
            "EV_ICE_Training_STRICT.xlsx"
        )
    )

    if not matches:
        raise FileNotFoundError(
            "Could not find "
            "EV_ICE_Training_STRICT.xlsx\n"
            f"inside:\n{part1_project}"
        )

    if len(matches) > 1:

        print(
            "\nMultiple STRICT training "
            "workbooks found:"
        )

        for path in matches:
            print(f"  - {path}")

        print(
            "\nUsing the most recently "
            "modified workbook."
        )

    training_file = max(
        matches,
        key=lambda path: path.stat().st_mtime,
    )

    return training_file


# ============================================================
# COLUMN VALIDATION
# ============================================================

def validate_columns(
    dataframe: pd.DataFrame,
) -> dict:
    """
    Check whether the expected ICE features,
    EV targets and metadata are present.

    No data is modified.
    """

    actual_columns = list(
        dataframe.columns
    )

    missing_ice = [
        column
        for column in ICE_FEATURES
        if column not in actual_columns
    ]

    missing_ev = [
        column
        for column in EV_TARGETS
        if column not in actual_columns
    ]

    missing_metadata = [
        column
        for column in REQUIRED_METADATA
        if column not in actual_columns
    ]

    duplicate_columns = (
        dataframe.columns[
            dataframe.columns.duplicated()
        ].tolist()
    )

    return {
        "missing_ice": missing_ice,
        "missing_ev": missing_ev,
        "missing_metadata": missing_metadata,
        "duplicate_columns": duplicate_columns,
        "ice_found": (
            len(ICE_FEATURES)
            - len(missing_ice)
        ),
        "ev_found": (
            len(EV_TARGETS)
            - len(missing_ev)
        ),
    }


# ============================================================
# NUMERIC VALIDATION
# ============================================================

def validate_numeric_columns(
    dataframe: pd.DataFrame,
    columns: list[str],
) -> dict:
    """
    Check whether modelling columns can be
    interpreted as numeric values.

    No data is modified.
    """

    results = {}

    for column in columns:

        if column not in dataframe.columns:
            continue

        original = dataframe[column]

        numeric = pd.to_numeric(
            original,
            errors="coerce",
        )

        conversion_failures = (
            original.notna()
            & numeric.isna()
        )

        numeric_values = numeric.dropna()

        if len(numeric_values) > 0:

            finite_mask = np.isfinite(
                numeric_values.to_numpy(
                    dtype=float
                )
            )

            finite_count = int(
                finite_mask.sum()
            )

            infinite_count = int(
                (~finite_mask).sum()
            )

        else:

            finite_count = 0
            infinite_count = 0

        results[column] = {
            "missing": int(
                original.isna().sum()
            ),
            "conversion_failures": int(
                conversion_failures.sum()
            ),
            "finite_values": finite_count,
            "infinite_values": infinite_count,
        }

    return results


# ============================================================
# VARIANCE / INFORMATION REPORT
# ============================================================

def calculate_variance_report(
    dataframe: pd.DataFrame,
    columns: list[str],
) -> pd.DataFrame:
    """
    Calculate descriptive and variance information.

    Nothing is removed based on this report.
    """

    rows = []

    for column in columns:

        if column not in dataframe.columns:
            continue

        values = pd.to_numeric(
            dataframe[column],
            errors="coerce",
        )

        non_null = values.dropna()

        if len(non_null) > 0:

            mean_value = float(
                non_null.mean()
            )

            std_value = float(
                non_null.std()
            )

            min_value = float(
                non_null.min()
            )

            max_value = float(
                non_null.max()
            )

        else:

            mean_value = np.nan
            std_value = np.nan
            min_value = np.nan
            max_value = np.nan

        unique_count = int(
            values.nunique(
                dropna=True
            )
        )

        rows.append(
            {
                "Feature": column,
                "Count": int(
                    values.notna().sum()
                ),
                "Missing": int(
                    values.isna().sum()
                ),
                "Unique": unique_count,
                "Mean": mean_value,
                "Std": std_value,
                "Min": min_value,
                "Max": max_value,
                "Constant": (
                    unique_count <= 1
                ),
            }
        )

    return pd.DataFrame(
        rows,
        columns=[
            "Feature",
            "Count",
            "Missing",
            "Unique",
            "Mean",
            "Std",
            "Min",
            "Max",
            "Constant",
        ],
    )


# ============================================================
# NON-NEGATIVE VALIDATION
# ============================================================

def validate_non_negative(
    dataframe: pd.DataFrame,
    columns: list[str],
) -> dict:
    """
    Check for negative physical values.

    No values are changed.
    """

    results = {}

    for column in columns:

        if column not in dataframe.columns:
            continue

        values = pd.to_numeric(
            dataframe[column],
            errors="coerce",
        )

        results[column] = int(
            (values < 0).sum()
        )

    return results


# ============================================================
# TARGET-SPECIFIC VALIDATION
# ============================================================

def validate_targets(
    dataframe: pd.DataFrame,
) -> dict:
    """
    Validate the 17 EV targets.

    Constant targets are reported only.
    They are NOT removed.
    """

    report = {}

    for target in EV_TARGETS:

        if target not in dataframe.columns:
            continue

        values = pd.to_numeric(
            dataframe[target],
            errors="coerce",
        )

        report[target] = {
            "missing": int(
                values.isna().sum()
            ),
            "unique_values": int(
                values.nunique(
                    dropna=True
                )
            ),
            "constant": (
                values.nunique(
                    dropna=True
                ) <= 1
            ),
            "negative_values": int(
                (values < 0).sum()
            ),
        }

    return report


# ============================================================
# PAIR ID VALIDATION
# ============================================================

def validate_pair_ids(
    dataframe: pd.DataFrame,
) -> dict:
    """
    Validate Pair ID information.

    Pair ID is used only as a grouping/
    identification variable.
    """

    if "Pair ID" not in dataframe.columns:

        return {
            "exists": False,
            "unique_pairs": None,
            "missing_pair_ids": None,
            "duplicate_pair_ids": None,
        }

    pair_ids = dataframe["Pair ID"]

    unique_pairs = int(
        pair_ids.nunique(
            dropna=True
        )
    )

    missing_pair_ids = int(
        pair_ids.isna().sum()
    )

    duplicate_pair_ids = int(
        pair_ids.duplicated(
            keep=False
        ).sum()
    )

    return {
        "exists": True,
        "unique_pairs": unique_pairs,
        "missing_pair_ids": missing_pair_ids,
        "duplicate_pair_ids": duplicate_pair_ids,
    }


# ============================================================
# DUPLICATE ROW VALIDATION
# ============================================================

def validate_duplicate_rows(
    dataframe: pd.DataFrame,
) -> dict:
    """
    Check for exact duplicate rows.

    Duplicate rows are NOT removed.
    """

    duplicate_mask = dataframe.duplicated(
        keep=False
    )

    return {
        "duplicate_rows": int(
            dataframe.duplicated().sum()
        ),
        "duplicate_group_rows": int(
            duplicate_mask.sum()
        ),
    }


# ============================================================
# MODELLING READINESS
# ============================================================

def determine_modelling_readiness(
    column_report: dict,
    numeric_report: dict,
) -> dict:
    """
    Determine whether the dataset is structurally
    ready to proceed.

    Warnings such as constant features/targets
    do NOT cause a structural failure.
    """

    structural_errors = []

    if column_report["missing_ice"]:

        structural_errors.append(
            "Missing ICE input features."
        )

    if column_report["missing_ev"]:

        structural_errors.append(
            "Missing EV target variables."
        )

    if column_report[
        "missing_metadata"
    ]:

        structural_errors.append(
            "Missing required metadata."
        )

    if column_report[
        "duplicate_columns"
    ]:

        structural_errors.append(
            "Duplicate column names detected."
        )

    conversion_failures = {
        column: report[
            "conversion_failures"
        ]
        for column, report
        in numeric_report.items()
        if report[
            "conversion_failures"
        ] > 0
    }

    if conversion_failures:

        structural_errors.append(
            "Numeric conversion failures "
            "detected."
        )

    infinite_values = {
        column: report[
            "infinite_values"
        ]
        for column, report
        in numeric_report.items()
        if report[
            "infinite_values"
        ] > 0
    }

    if infinite_values:

        structural_errors.append(
            "Infinite values detected."
        )

    if structural_errors:

        status = "FAIL"

    else:

        status = "PASS"

    return {
        "status": status,
        "errors": structural_errors,
        "warnings": [],
    }


